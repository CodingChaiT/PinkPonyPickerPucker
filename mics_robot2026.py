class ArmController:
    """Controls the arm (300° servo) and gripper (180° servo) via GPIO PWM."""

    def __init__(self):
        self._arm_pwm     = None
        self._gripper_pwm = None

        if HARDWARE_AVAILABLE:
            GPIO.setup(ARM_PIN,     GPIO.OUT)
            GPIO.setup(GRIPPER_PIN, GPIO.OUT)
            self._arm_pwm     = GPIO.PWM(ARM_PIN,     50)
            self._gripper_pwm = GPIO.PWM(GRIPPER_PIN, 50)
            self._arm_pwm.start(0)
            self._gripper_pwm.start(0)

        # Safe starting position
        self.arm_up()
        self.gripper_open()

    def _set_arm(self, angle: float, settle: float = 0.6):
        duty = 2.5 + (angle / 300.0) * 10.0
        if HARDWARE_AVAILABLE:
            self._arm_pwm.ChangeDutyCycle(duty)
            time.sleep(settle)
            self._arm_pwm.ChangeDutyCycle(0)
        else:
            print(f"  [ARM] → {angle}°")
            time.sleep(settle)

    def _set_gripper(self, angle: float, settle: float = 0.5):
        duty = 2.5 + (angle / 18.0)
        if HARDWARE_AVAILABLE:
            self._gripper_pwm.ChangeDutyCycle(duty)
            time.sleep(settle)
            self._gripper_pwm.ChangeDutyCycle(0)
        else:
            print(f"  [GRIPPER] → {angle}°")
            time.sleep(settle)

    def arm_up(self):        self._set_arm(ARM_UP_ANGLE)
    def arm_down(self):      self._set_arm(ARM_DOWN_ANGLE)
    def gripper_open(self):  self._set_gripper(GRIPPER_OPEN)
    def gripper_close(self): self._set_gripper(GRIPPER_CLOSED)

    def cleanup(self):
        if HARDWARE_AVAILABLE and self._arm_pwm:
            self._arm_pwm.stop()
            self._gripper_pwm.stop()


