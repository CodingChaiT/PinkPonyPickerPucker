class MecanumGUI:
    def __init__(self, root: tk.Tk, motor_ctrl: MotorController):
        self.root = root
        self.mc = motor_ctrl
        self._active_move = None
        self._repeat_thread = None
        self._running = True

        self._build_window()
        self._build_header()
        self._build_dpad()
        self._build_status_bar()
        self._bind_keyboard()

        # Graceful shutdown
        self.root.protocol("WM_DELETE_WINDOW", self._on_close)

    # ── Window setup ──────────────────────────────────────────────────────────

    def _build_window(self):
        self.root.title("Mecanum Wheel Controller")
        self.root.configure(bg=BG)
        self.root.resizable(False, False)
        self.root.geometry("480x560")

    # ── Header ────────────────────────────────────────────────────────────────

    def _build_header(self):
        header = tk.Frame(self.root, bg=BG, pady=18)
        header.pack(fill="x")

        try:
            title_font = tkfont.Font(family="Courier New", size=16, weight="bold")
        except Exception:
            title_font = ("TkFixedFont", 16, "bold")

        tk.Label(
            header, text="◈  MECANUM DRIVE  ◈",
            font=title_font, fg=ACCENT, bg=BG
        ).pack()

        mode_text = "HARDWARE" if HARDWARE_AVAILABLE else "SIMULATION MODE"
        mode_col  = "#44cc88" if HARDWARE_AVAILABLE else "#cc8844"
        tk.Label(
            header, text=f"● {mode_text}",
            font=("Courier New", 9), fg=mode_col, bg=BG
        ).pack(pady=(2, 0))

    # ── D-pad ─────────────────────────────────────────────────────────────────

    def _build_dpad(self):
        """Build a 3×3 grid of direction buttons."""
        outer = tk.Frame(self.root, bg=BG)
        outer.pack(expand=True)

        pad = tk.Frame(outer, bg=PANEL, padx=20, pady=20,
                       highlightbackground=BORDER, highlightthickness=1)
        pad.pack()

        # Grid layout: (row, col) → (label, move_key)
        layout = [
            (0, 0, "↖",  "fwd_left"),
            (0, 1, "↑",  "forward"),
            (0, 2, "↗",  "fwd_right"),
            (1, 0, "←",  "left"),
            (1, 1, "■",  "stop"),       # centre stop
            (1, 2, "→",  "right"),
            (2, 0, "↙",  "bck_left"),
            (2, 1, "↓",  "backward"),
            (2, 2, "↘",  "bck_right"),
        ]

        self._buttons = {}

        for row, col, symbol, move in layout:
            is_stop = (move == "stop")
            btn = self._make_button(pad, symbol, move, is_stop)
            btn.grid(row=row, column=col, padx=6, pady=6)
            self._buttons[move] = btn

        # Speed slider
        slider_frame = tk.Frame(outer, bg=BG, pady=14)
        slider_frame.pack(fill="x")

        tk.Label(slider_frame, text="SPEED", font=("Courier New", 9),
                 fg=FG_LABEL, bg=BG).pack(side="left", padx=(20, 8))

        self._speed_var = tk.DoubleVar(value=SPEED)
        slider = tk.Scale(
            slider_frame, from_=0.1, to=1.0, resolution=0.05,
            orient="horizontal", variable=self._speed_var,
            command=self._on_speed_change,
            bg=PANEL, fg=FG_STATUS, troughcolor=BUTTON_IDLE,
            highlightthickness=0, activebackground=BUTTON_HOV,
            length=280, bd=0, relief="flat"
        )
        slider.pack(side="left")

    def _make_button(self, parent, symbol: str, move: str, is_stop: bool):
        idle = STOP_IDLE if is_stop else BUTTON_IDLE
        act  = STOP_ACT  if is_stop else BUTTON_ACT

        try:
            arrow_font = tkfont.Font(family="Courier New", size=22, weight="bold")
        except Exception:
            arrow_font = ("TkFixedFont", 22, "bold")

        btn = tk.Label(
            parent, text=symbol, width=3, height=1,
            font=arrow_font, fg=FG_STATUS, bg=idle,
            relief="flat", cursor="hand2",
            highlightbackground=BORDER, highlightthickness=1,
            padx=10, pady=10
        )

        # Bind press / release
        btn.bind("<ButtonPress-1>",   lambda e, m=move, i=idle, a=act, b=btn:
                                      self._on_press(m, b, i, a))
        btn.bind("<ButtonRelease-1>", lambda e, m=move, i=idle, b=btn:
                                      self._on_release(m, b, i))
        btn.bind("<Enter>",  lambda e, b=btn, i=idle: b.config(bg=BUTTON_HOV if i != STOP_IDLE else "#3a1a1a"))
        btn.bind("<Leave>",  lambda e, b=btn, i=idle: b.config(bg=i) if self._active_move != move else None)

        return btn

    # ── Button event handlers ─────────────────────────────────────────────────

    def _on_press(self, move: str, btn: tk.Label, idle_col: str, act_col: str):
        btn.config(bg=act_col)
        self._active_move = move
        self._apply_move(move)

        # Start auto-repeat thread
        self._running_move = True
        self._repeat_thread = threading.Thread(
            target=self._repeat_move, args=(move,), daemon=True
        )
        self._repeat_thread.start()

        self._update_status(move)

    def _on_release(self, move: str, btn: tk.Label, idle_col: str):
        btn.config(bg=idle_col)
        self._running_move = False
        self._active_move = None
        self._apply_move("stop")
        self._update_status("stop")

    def _repeat_move(self, move: str):
        """Keep sending motor commands while button is held (prevents timeout stall)."""
        time.sleep(0.1)  # initial delay
        while self._running_move and self._active_move == move:
            self._apply_move(move)
            time.sleep(STEP_INTERVAL)

    def _apply_move(self, move: str):
        fl, fr, rl, rr = MOVES[move]
        self.mc.set_motors(fl, fr, rl, rr)

    # ── Speed slider ──────────────────────────────────────────────────────────

    def _on_speed_change(self, val):
        global SPEED, DIAG_SPEED, MOVES
        s = float(val)
        SPEED = s
        DIAG_SPEED = s
        # Rebuild MOVES table with new speed
        MOVES["forward"]   = (+s, +s, +s, +s)
        MOVES["backward"]  = (-s, -s, -s, -s)
        MOVES["left"]      = (-s, +s, +s, -s)
        MOVES["right"]     = (+s, -s, -s, +s)
        MOVES["fwd_left"]  = (0,  +s,  +s,  0)
        MOVES["fwd_right"] = (+s,  0,   0, +s)
        MOVES["bck_left"]  = (-s,  0,   0, -s)
        MOVES["bck_right"] = (0,  -s,  -s,  0)

    # ── Keyboard bindings ─────────────────────────────────────────────────────

    KEY_MAP = {
        "w": "forward",   "Up":    "forward",
        "s": "backward",  "Down":  "backward",
        "a": "left",      "Left":  "left",
        "d": "right",     "Right": "right",
        "q": "fwd_left",
        "e": "fwd_right",
        "z": "bck_left",
        "c": "bck_right",
        "space": "stop",
    }

    def _bind_keyboard(self):
        for key, move in self.KEY_MAP.items():
            self.root.bind(f"<KeyPress-{key}>",   lambda e, m=move: self._kbd_press(m))
            self.root.bind(f"<KeyRelease-{key}>", lambda e: self._kbd_release())

    def _kbd_press(self, move: str):
        if self._active_move == move:
            return   # already running
        self._active_move = move
        self._apply_move(move)
        self._update_status(move)
        # Highlight button
        btn = self._buttons.get(move)
        if btn:
            act = STOP_ACT if move == "stop" else BUTTON_ACT
            btn.config(bg=act)

    def _kbd_release(self):
        old = self._active_move
        self._active_move = None
        self._apply_move("stop")
        self._update_status("stop")
        if old:
            btn = self._buttons.get(old)
            if btn:
                idle = STOP_IDLE if old == "stop" else BUTTON_IDLE
                btn.config(bg=idle)

    # ── Status bar ────────────────────────────────────────────────────────────

    MOVE_LABELS = {
        "forward":   "▲  FORWARD",
        "backward":  "▼  BACKWARD",
        "left":      "◀  STRAFE LEFT",
        "right":     "▶  STRAFE RIGHT",
        "fwd_left":  "↖  FORWARD-LEFT",
        "fwd_right": "↗  FORWARD-RIGHT",
        "bck_left":  "↙  BACKWARD-LEFT",
        "bck_right": "↘  BACKWARD-RIGHT",
        "stop":      "■  STOPPED",
    }

    def _build_status_bar(self):
        bar = tk.Frame(self.root, bg=PANEL, pady=10,
                       highlightbackground=BORDER, highlightthickness=1)
        bar.pack(fill="x", side="bottom")

        try:
            status_font = tkfont.Font(family="Courier New", size=11, weight="bold")
        except Exception:
            status_font = ("TkFixedFont", 11, "bold")

        self._status_var = tk.StringVar(value="■  STOPPED")
        tk.Label(bar, textvariable=self._status_var,
                 font=status_font, fg=FG_STATUS, bg=PANEL).pack()

        hint = "WASD / Arrow keys  |  Q E Z C = diagonals  |  Space = stop"
        tk.Label(bar, text=hint, font=("Courier New", 8),
                 fg=FG_LABEL, bg=PANEL).pack(pady=(2, 0))

    def _update_status(self, move: str):
        label = self.MOVE_LABELS.get(move, "■  STOPPED")
        self._status_var.set(label)

    # ── Shutdown ──────────────────────────────────────────────────────────────

    def _on_close(self):
        self._running_move = False
        self._running = False
        self.mc.cleanup()
        self.root.destroy()


