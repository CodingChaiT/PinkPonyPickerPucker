class GrabConfirmDialog(tk.Toplevel):
    """
    Modal Yes / No dialog shown after the gripper closes.
    Must be created on the Tk main thread.
    Sets result[0] and fires event when the operator answers.
    Keyboard shortcuts: Y = yes, N = no.
    """

