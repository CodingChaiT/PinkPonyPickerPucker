SPEED = 0.8          # Throttle for cardinal directions  (0.0 – 1.0)
DIAG_SPEED = 0.8     # Throttle for diagonal directions  (0.0 – 1.0)
STEP_INTERVAL = 0.05  # Seconds between repeated move pulses while button held
PWM_FREQ = 100        # Hz – PWM frequency for motor enable pins

# Flip any wheel that spins the wrong way (+1 = normal, -1 = reversed)
MOTOR_POLARITY = {
    "fl": -1,   # Front-Left
    "fr": -1,   # Front-Right  (mirrored mount → usually needs flip)
    "rl": -1,   # Rear-Left
    "rr": -1,   # Rear-Right   (mirrored mount → usually needs flip)
}

# SB Components Motor Shield – physical BOARD pin numbers
# Each entry: (enable_pin, forward_pin, reverse_pin)
MOTOR_PINS = {
    "MOTOR1": (11, 15, 13),   # Front-Left
    "MOTOR2": (22, 16, 18),   # Front-Right
    "MOTOR3": (19, 21, 23),   # Rear-Left
    "MOTOR4": (32, 24, 26),   # Rear-Right
}


# ═══════════════════════════════════════════════════════════════════════════════
#  MOTOR HARDWARE LAYER
# ═══════════════════════════════════════════════════════════════════════════════

class MotorController:
    """
    Wrapper around RPi.GPIO for the SB Components Motor Shield.
    Exposes set_motors(fl, fr, rl, rr); each argument is a throttle
    in the range [-1.0, 1.0].
    """

    def __init__(self):
        self._pwm = {}   # motor_key → GPIO.PWM object

        if HARDWARE_AVAILABLE:
            GPIO.setmode(GPIO.BOARD)
            GPIO.setwarnings(False)

            motor_keys = ["fl", "fr", "rl", "rr"]
            motor_names = ["MOTOR1", "MOTOR2", "MOTOR3", "MOTOR4"]

            for key, name in zip(motor_keys, motor_names):
                en_pin, fwd_pin, rev_pin = MOTOR_PINS[name]
                GPIO.setup(en_pin,  GPIO.OUT)
                GPIO.setup(fwd_pin, GPIO.OUT)
                GPIO.setup(rev_pin, GPIO.OUT)

                # Start PWM at 0% duty cycle (stopped)
                pwm = GPIO.PWM(en_pin, PWM_FREQ)
                pwm.start(0)
                self._pwm[key] = (pwm, fwd_pin, rev_pin)

    def _drive(self, key: str, throttle: float):
        """Send a single motor command: throttle in [-1.0, 1.0]."""
        throttle = max(-1.0, min(1.0, throttle)) * MOTOR_POLARITY[key]
        duty = abs(throttle) * 100.0   # convert to 0-100% duty cycle

        if HARDWARE_AVAILABLE:
            pwm, fwd_pin, rev_pin = self._pwm[key]
            if throttle > 0:
                GPIO.output(fwd_pin, GPIO.HIGH)
                GPIO.output(rev_pin, GPIO.LOW)
            elif throttle < 0:
                GPIO.output(fwd_pin, GPIO.LOW)
                GPIO.output(rev_pin, GPIO.HIGH)
            else:
                GPIO.output(fwd_pin, GPIO.LOW)
                GPIO.output(rev_pin, GPIO.LOW)
            pwm.ChangeDutyCycle(duty)

    def set_motors(self, fl: float, fr: float, rl: float, rr: float):
        """Apply polarity correction and send throttle to each motor."""
        if not HARDWARE_AVAILABLE:
            p = MOTOR_POLARITY
            print(f"  FL={fl * p['fl']:+.2f}  FR={fr * p['fr']:+.2f}  "
                  f"RL={rl * p['rl']:+.2f}  RR={rr * p['rr']:+.2f}")
            return

        self._drive("fl", fl)
        self._drive("fr", fr)
        self._drive("rl", rl)
        self._drive("rr", rr)

    def stop(self):
        self.set_motors(0, 0, 0, 0)

    def cleanup(self):
        self.stop()
        if HARDWARE_AVAILABLE:
            for pwm, _, _ in self._pwm.values():
                pwm.stop()
            GPIO.cleanup()


# ═══════════════════════════════════════════════════════════════════════════════
#  MECANUM MOTION VECTORS
#  Formula: FL = Vy + Vx,  FR = Vy - Vx,  RL = Vy - Vx,  RR = Vy + Vx
#  where Vy = forward/backward,  Vx = left/right strafe
# ═══════════════════════════════════════════════════════════════════════════════

S = SPEED
D = DIAG_SPEED

MOVES = {
    #              FL    FR    RL    RR
    "forward":  ( +S,   +S,   +S,   +S),
    "backward": ( -S,   -S,   -S,   -S),
    "left":     ( -S,   +S,   +S,   -S),
    "right":    ( +S,   -S,   -S,   +S),
    "fwd_left": (  0,   +D,   +D,    0),   # ↖ diagonal
    "fwd_right":(  +D,   0,    0,   +D),   # ↗ diagonal
    "bck_left": ( -D,    0,    0,   -D),   # ↙ diagonal
    "bck_right":(   0,  -D,   -D,    0),   # ↘ diagonal
    "stop":     (  0,    0,    0,    0),
}


