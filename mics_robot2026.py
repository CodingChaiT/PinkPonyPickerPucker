def classify_color(h, s, v):
    if s < 60 or v < 60:
        return "None"
    elif h >= 80 and h <= 105:
        return "Yellow"
    if (h >= 0 and h <= 10) or (h >= 170 and h <= 179):
        return "Blue"
    elif h >= 90 and h <= 140:
        return "Red"
    elif h >= 40 and h <= 80:
        return "Green"
    return "None"


def estimate_distance(radius):
    if radius == 0:
        return 999
    return int(1000 / radius)


# ═══════════════════════════════════════════════════════════════════════════════
#  CAMERA / AUTO THREAD
# ═══════════════════════════════════════════════════════════════════════════════

class CameraThread(threading.Thread):

    def __init__(self, mc: MotorController, arm: ArmController,
                 state: dict, gui_ref):
        super().__init__(daemon=True)
        self.mc    = mc
        self.arm   = arm
        self.state = state
        self.gui   = gui_ref   # set to RobotGUI after Tk is created

    # ── Main camera loop ──────────────────────────────────────────────────────

    def run(self):
        picam2 = Picamera2()
        picam2.configure(picam2.create_preview_configuration(
            main={"format": "RGB888", "size": (CAPTURE_W, CAPTURE_H)}
        ))
        picam2.start()
        time.sleep(1)

        while self.state["running"]:
            frame = picam2.capture_array()
            # Resize from the wider capture resolution back to processing size.
            # This preserves the larger FOV while keeping all detection logic
            # and display coordinates based on FRAME_W x FRAME_H as before.
            if FOV_SCALE != 1:
                frame = cv2.resize(frame, (FRAME_W, FRAME_H),
                                   interpolation=cv2.INTER_AREA)
            hsv   = cv2.cvtColor(frame, cv2.COLOR_RGB2HSV)

            # ══════════════════════════════════════════════════════════════════
            #  OBJECT DETECTION  –  three classes: PUCK / HOME / ROBOT
            #
            #  All three share one colour mask so we only do the HSV work once.
            #  Classification rules:
            #    PUCK   – target colour  +  circular (circ >= MIN_CIRCULARITY)
            #                            +  PUCK_MIN_AREA <= area <= PUCK_MAX_AREA
            #    HOME   – target colour  +  area >= HOME_MIN_AREA
            #                            +  centroid in top HOME_MAX_Y_FRAC of frame
            #    ROBOT  – any colour     +  ROBOT_MIN_AREA <= area <= ROBOT_MAX_AREA
            #                            +  NOT circular (circ < ROBOT_MAX_CIRC)
            #                            +  centroid NOT in top half of frame
            # ══════════════════════════════════════════════════════════════════

            # ── Broad colour mask (all saturated colours) ─────────────────────
            mask = cv2.inRange(hsv, np.array([0, 60, 60]), np.array([179, 255, 255]))
            mask = cv2.morphologyEx(mask, cv2.MORPH_OPEN,  np.ones((5, 5), np.uint8))
            mask = cv2.morphologyEx(mask, cv2.MORPH_CLOSE, np.ones((7, 7), np.uint8))
            contours, _ = cv2.findContours(mask, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)

            best_puck  = None   # (cx, cy, radius, dist_cm)  – best target puck this frame
            best_puck_area = 0
            home_zones = []     # [(cx, cy, area)]
            robots     = []     # [(cx, cy, area, side)]  side: "left"/"right"/"centre"

            for c in contours:
                area = cv2.contourArea(c)
                if area < PUCK_MIN_AREA:
                    continue  # too small to care about

                peri = cv2.arcLength(c, True)
                circ = (4 * np.pi * area / (peri * peri)) if peri > 0 else 0

                (cx, cy), r = cv2.minEnclosingCircle(c)
                cx, cy, r   = int(cx), int(cy), int(r)

                # Sample colour at centroid
                roi = hsv[max(0, cy-6):cy+6, max(0, cx-6):cx+6]
                if roi.size == 0:
                    continue
                h_v, s_v, v_v = np.mean(roi, axis=(0, 1)).astype(int)
                color = classify_color(h_v, s_v, v_v)
                is_target_color = (color == self.state["target"])
                in_top_half     = (cy < FRAME_H * HOME_MAX_Y_FRAC)

                # ── Classify ──────────────────────────────────────────────────

                # HOME ZONE: target colour, large, centroid in top half
                if (is_target_color
                        and area >= HOME_MIN_AREA
                        and in_top_half):
                    home_zones.append((cx, cy, area))
                    # Draw: thick gold rectangle around bounding box
                    bx, by, bw, bh = cv2.boundingRect(c)
                    cv2.rectangle(frame, (bx, by), (bx+bw, by+bh), (0, 215, 255), 3)
                    cv2.putText(frame, "HOME",
                                (bx, by - 8),
                                cv2.FONT_HERSHEY_SIMPLEX, 0.7, (0, 215, 255), 2)
                    continue

                # PUCK: target colour, circular, right size
                if (is_target_color
                        and PUCK_MIN_AREA <= area <= PUCK_MAX_AREA
                        and circ >= MIN_CIRCULARITY):
                    dist = estimate_distance(r)
                    if area > best_puck_area:
                        best_puck_area = area
                        best_puck = (cx, cy, r, dist)
                    # Draw: bright red ring + crosshair
                    cv2.circle(frame, (cx, cy), r, (0, 0, 255), 4)
                    cv2.line(frame,  (cx-16, cy), (cx+16, cy), (0, 0, 255), 2)
                    cv2.line(frame,  (cx, cy-16), (cx, cy+16), (0, 0, 255), 2)
                    cv2.putText(frame, f"{color} {dist}cm",
                                (cx - 40, cy - r - 10),
                                cv2.FONT_HERSHEY_SIMPLEX, 0.6, (255, 255, 255), 2)
                    continue

                # ROBOT: any colour, mid-size, non-circular, not in top half
                if (ROBOT_MIN_AREA <= area <= ROBOT_MAX_AREA
                        and circ < ROBOT_MAX_CIRC
                        and not in_top_half):
                    # Determine which side of the frame the robot is on
                    rel = cx / FRAME_W   # 0=far left, 1=far right
                    if rel < (0.5 - ROBOT_AVOID_FRAC / 2):
                        side = "left"
                    elif rel > (0.5 + ROBOT_AVOID_FRAC / 2):
                        side = "right"
                    else:
                        side = "centre"
                    robots.append((cx, cy, area, side))
                    # Draw: orange polygon outline + label
                    cv2.drawContours(frame, [c], -1, (0, 140, 255), 3)
                    cv2.putText(frame, f"ROBOT ({side})",
                                (cx - 50, cy - r - 10),
                                cv2.FONT_HERSHEY_SIMPLEX, 0.6, (0, 140, 255), 2)
                    continue

                # Everything else – draw a dim grey ring (non-target, non-robot)
                if is_target_color:
                    cv2.circle(frame, (cx, cy), r, (200, 200, 200), 1)

            # Convenience alias used throughout the rest of the loop
            best = best_puck

            # ── AUTO drive logic ──────────────────────────────────────────────
            if self.state["auto"] and not self.state["estop"]:

                if self.state["pickup_active"]:
                    # Pickup / confirm / return thread owns the robot – hold still
                    self.mc.stop()

                elif self.state["blind_driving"]:
                    # Puck disappeared under camera – creep until timer expires
                    elapsed_blind = time.monotonic() - self.state["_blind_start"]
                    if elapsed_blind >= BLIND_DRIVE_SECS:
                        self.mc.stop()
                        self.state["blind_driving"] = False
                        if not self.state["pickup_active"]:
                            self.state["pickup_active"] = True
                            threading.Thread(
                                target=self._run_pickup_sequence,
                                daemon=True
                            ).start()
                    else:
                        self._accum_odometry()
                        self.mc.forward(CREEP_SPEED)

                elif best:
                    # Puck visible – reset search timer, then check for robots
                    self.state["_search_start"] = None
                    x, y, r, dist = best
                    offset = x - FRAME_W // 2

                    # ── Robot avoidance (overrides puck tracking) ─────────────
                    # Find the closest robot (largest area = nearest)
                    blocking = self._blocking_robot(robots, offset)
                    if blocking is not None:
                        self._commit_odometry()
                        self._do_avoidance(blocking)

                    elif r >= PICKUP_RADIUS:
                        # Close enough – commit odometry and begin blind drive-in
                        self._commit_odometry()
                        self.state["blind_driving"] = True
                        self.state["_blind_start"]  = time.monotonic()
                        self.mc.forward(CREEP_SPEED)

                    elif offset < -CENTER_TOLERANCE:
                        self._commit_odometry()
                        self.mc.left()

                    elif offset > CENTER_TOLERANCE:
                        self._commit_odometry()
                        self.mc.right()

                    else:
                        # Centred and no obstacle – drive forward, accumulate odometry
                        self._accum_odometry()
                        self.mc.forward()

                else:
                    # ── No puck visible: slow alternating search spin ─────────
                    self._commit_odometry()
                    now = time.monotonic()

                    if self.state["_search_start"] is None:
                        self.state["_search_start"] = now

                    if now - self.state["_search_start"] >= SEARCH_SWEEP_SEC:
                        # Reverse spin direction and restart sweep timer
                        self.state["_search_dir"]  = -self.state["_search_dir"]
                        self.state["_search_start"] = now

                    if self.state["_search_dir"] > 0:
                        self.mc.spin_right(SEARCH_SPEED)
                    else:
                        self.mc.spin_left(SEARCH_SPEED)

            else:
                # Manual / e-stop – commit any open odometry and clear search
                self._commit_odometry()
                self.state["blind_driving"]  = False
                self.state["_search_start"]  = None

            # ── HUD ───────────────────────────────────────────────────────────
            self._draw_hud(frame, best, robots, home_zones)
            cv2.imshow("Robot Camera", frame)
            cv2.waitKey(1)

        picam2.stop()
        cv2.destroyAllWindows()

    # ── Robot avoidance helpers ───────────────────────────────────────────────

    def _blocking_robot(self, robots: list, puck_offset: int):
        """
        Return the most threatening robot entry, or None.
        A robot is "blocking" if its centre is within ROBOT_AVOID_FRAC of the
        frame centre horizontally AND it is in the lower half of the frame
        (i.e. actually between us and the puck, not off to the side).
        """
        if not robots:
            return None
        # Filter to robots that are roughly in our forward path
        blocking = [
            r for r in robots
            if r[3] in ("centre", "left", "right")   # all visible robots count
        ]
        if not blocking:
            return None
        # Pick the one with the largest area (= closest)
        return max(blocking, key=lambda r: r[2])

    def _do_avoidance(self, robot: tuple):
        """
        Steer away from a detected robot for AVOID_TURN_SECS then stop
        (the main loop will re-evaluate next frame).
        Steers opposite to whichever side the robot is on.
        Robot is (cx, cy, area, side).
        """
        _, _, _, side = robot
        # Steer opposite to the robot's side
        if side == "right":
            print(f"[AVOID] robot on RIGHT – steering left")
            self.mc.fwd_left(SPEED)
        elif side == "left":
            print(f"[AVOID] robot on LEFT – steering right")
            self.mc.fwd_right(SPEED)
        else:
            # Robot dead ahead – steer right by default
            print(f"[AVOID] robot CENTRE – steering right")
            self.mc.fwd_right(SPEED)
        # Hold the turn briefly; the camera loop will re-evaluate next iteration
        time.sleep(AVOID_TURN_SECS)

    # ── Odometry helpers ──────────────────────────────────────────────────────

    def _accum_odometry(self):
        """Begin or continue timing a forward-drive interval."""
        if self.state["_fwd_start"] is None:
            self.state["_fwd_start"] = time.monotonic()

    def _commit_odometry(self):
        """Freeze the current interval into forward_cm."""
        if self.state["_fwd_start"] is not None:
            elapsed = time.monotonic() - self.state["_fwd_start"]
            self.state["forward_cm"] += elapsed * FORWARD_CM_PER_SEC
            self.state["_fwd_start"]  = None

    # ── Pickup sequence ───────────────────────────────────────────────────────

    def _run_pickup_sequence(self):
        """Lower arm, close gripper, wait for operator confirmation."""
        self._commit_odometry()
        print(f"[PICKUP] total approach: {self.state['forward_cm']:.1f} cm")

        print("[PICKUP] lowering arm...")
        self.arm.arm_down()

        print("[PICKUP] closing gripper...")
        self.arm.gripper_close()

        print("[PICKUP] awaiting operator confirmation...")
        grabbed = self._ask_confirmation()

        if grabbed:
            print("[PICKUP] confirmed grabbed – returning to start.")
            self._run_return_sequence()
        else:
            print("[PICKUP] grab failed – opening, raising, backing off.")
            self._run_fail_sequence()

    # ── Confirmation dialog (thread-safe via root.after) ──────────────────────

    def _ask_confirmation(self) -> bool:
        """
        Post a Yes/No dialog onto the Tk main thread and block until answered.
        Returns True = grabbed, False = failed.
        """
        event  = threading.Event()
        result = [False]

        def _show():
            GrabConfirmDialog(self.gui.root, result, event)

        self.gui.root.after(0, _show)
        event.wait()
        return result[0]

    # ── Success: drive back the full approach distance and drop ───────────────

    def _run_return_sequence(self):
        distance_cm = self.state["forward_cm"]
        return_secs = distance_cm / FORWARD_CM_PER_SEC
        print(f"[RETURN] reversing {distance_cm:.1f} cm ({return_secs:.1f} s)...")

        self.mc.backward(SPEED)
        time.sleep(return_secs)
        self.mc.stop()

        print("[RETURN] dropping puck...")
        self.arm.gripper_open()
        time.sleep(0.3)

        print("[RETURN] raising arm...")
        self.arm.arm_up()

        # Reset everything for the next puck
        self.state["forward_cm"]    = 0.0
        self.state["_fwd_start"]    = None
        self.state["_search_start"] = None
        self.state["pickup_active"] = False
        print("[RETURN] done – resuming AUTO search.")

    # ── Failure: open gripper, raise arm, back off, resume search ─────────────

    def _run_fail_sequence(self):
        print("[FAIL] opening gripper...")
        self.arm.gripper_open()
        time.sleep(0.2)

        print("[FAIL] raising arm...")
        self.arm.arm_up()

        print(f"[FAIL] backing off {FAIL_BACKOFF_SECS} s...")
        self.mc.backward(SPEED)
        time.sleep(FAIL_BACKOFF_SECS)
        self.mc.stop()

        # Reset odometry – we've moved, start fresh
        self.state["forward_cm"]    = 0.0
        self.state["_fwd_start"]    = None
        self.state["_search_start"] = None
        self.state["pickup_active"] = False
        print("[FAIL] resuming AUTO search.")

    # ── HUD ───────────────────────────────────────────────────────────────────

    def _draw_hud(self, frame, best, robots=None, home_zones=None):
        robots     = robots     or []
        home_zones = home_zones or []
        mode   = "AUTO" if self.state["auto"] else "MANUAL"
        target = self.state["target"]
        estop  = self.state["estop"]
        pickup = self.state["pickup_active"]
        blind  = self.state["blind_driving"]
        fwd_cm = self.state["forward_cm"]
        searching = (not best and not blind and not pickup
                     and self.state["auto"] and not estop)

        lines = [
            f"MODE: {mode}   TARGET: {target}",
            ("PUCK: BLIND DRIVE-IN" if blind
             else f"PUCK: SEARCHING – {'RIGHT' if self.state['_search_dir']>0 else 'LEFT'}" if searching
             else f"PUCK: {'in range' if best else 'not seen'}"),
            f"DIST: {fwd_cm:.0f} cm  |  ROBOTS: {len(robots)}  |  HOME: {'seen' if home_zones else 'not seen'}",
        ]
        for i, line in enumerate(lines):
            cv2.putText(frame, line, (10, 28 + i * 26),
                        cv2.FONT_HERSHEY_SIMPLEX, 0.6, (220, 220, 220), 2)

        # Avoidance indicator: if a robot is detected draw a warning bar
        if robots and self.state["auto"] and not pickup and not blind:
            sides = [r[3] for r in robots]
            side_txt = " & ".join(sorted(set(sides)))
            cv2.rectangle(frame, (0, FRAME_H-55), (FRAME_W, FRAME_H), (0, 100, 200), -1)
            cv2.putText(frame, f"  ROBOT DETECTED ({side_txt}) – avoiding...",
                        (10, FRAME_H-16), cv2.FONT_HERSHEY_SIMPLEX, 0.72, (255,255,255), 2)
        elif estop:
            cv2.rectangle(frame, (0, FRAME_H-55), (FRAME_W, FRAME_H), (0, 0, 160), -1)
            cv2.putText(frame, "  E-STOP  (release Space to continue)",
                        (10, FRAME_H-16), cv2.FONT_HERSHEY_SIMPLEX, 0.75, (255,255,255), 2)
        elif pickup:
            cv2.rectangle(frame, (0, FRAME_H-55), (FRAME_W, FRAME_H), (0, 130, 0), -1)
            cv2.putText(frame, "  PICKUP – confirm grab on remote...",
                        (10, FRAME_H-16), cv2.FONT_HERSHEY_SIMPLEX, 0.75, (255,255,255), 2)
        elif blind:
            cv2.rectangle(frame, (0, FRAME_H-55), (FRAME_W, FRAME_H), (180, 100, 0), -1)
            cv2.putText(frame, "  BLIND DRIVE-IN – closing on puck...",
                        (10, FRAME_H-16), cv2.FONT_HERSHEY_SIMPLEX, 0.75, (255,255,255), 2)
        elif searching:
            dir_txt = "RIGHT" if self.state["_search_dir"] > 0 else "LEFT"
            cv2.rectangle(frame, (0, FRAME_H-55), (FRAME_W, FRAME_H), (80, 40, 120), -1)
            cv2.putText(frame, f"  SEARCHING – spinning {dir_txt}...",
                        (10, FRAME_H-16), cv2.FONT_HERSHEY_SIMPLEX, 0.75, (255,255,255), 2)


