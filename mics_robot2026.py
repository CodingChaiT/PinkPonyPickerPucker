FRAME_W          = 640
FRAME_H          = 480

# ── Wide-angle FOV (2x zoom-out) ──────────────────────────────────────────────
# Capture at 2× resolution from the sensor so we see twice as much of the scene,
# then resize back down to FRAME_W × FRAME_H for all detection & display work.
# If your Pi camera sensor tops out below 1280×960, lower the multiplier to 1.5.
FOV_SCALE        = 2          # capture resolution multiplier  (1 = no change)
CAPTURE_W        = FRAME_W * FOV_SCALE   # 1280
CAPTURE_H        = FRAME_H * FOV_SCALE   # 960

CENTER_TOLERANCE = 40     # px – strafe until puck centre is within this of frame centre
PICKUP_RADIUS    = 160    # px – switch to blind drive-in when puck radius reaches this

# ── Object detection thresholds ───────────────────────────────────────────────
# PUCK  – target colour, circular, small
PUCK_MIN_AREA    = 800    # px² – ignore anything smaller
PUCK_MAX_AREA    = 18000  # px² – above this it's a home zone, not a puck
MIN_CIRCULARITY  = 0.72   # 0–1; pucks score ~0.85+; tweak if mis-classifying

# HOME ZONE – same colour as target puck, large area, centroid in TOP half of frame
HOME_MIN_AREA    = 20000  # px² – home zone will be much bigger than a puck  ← tune
HOME_MAX_Y_FRAC  = 0.5    # centroid must be in top 50 % of frame

# OTHER ROBOTS – any colour, mid-size blob, low circularity, NOT in top half
ROBOT_MIN_AREA   = 5000   # px² – smallest blob we call a robot  ← tune
ROBOT_MAX_AREA   = 80000  # px² – upper limit (whole-frame noise guard)
ROBOT_MAX_CIRC   = 0.65   # robots are non-circular; reject above this
ROBOT_AVOID_FRAC = 0.35   # robot centre within this fraction of frame width triggers avoidance

# ── Avoidance ─────────────────────────────────────────────────────────────────
AVOID_TURN_SECS  = 0.4    # seconds to hold avoidance turn before re-evaluating

SPEED            = 0.6

# ── Search behaviour (no puck visible) ───────────────────────────────────────
# Robot alternates slow right / slow left sweeps while searching.
SEARCH_SPEED     = 0.25  # spin speed while searching  ← tune
SEARCH_SWEEP_SEC = 1.2   # seconds per sweep before reversing direction  ← tune

# ── Blind drive-in ────────────────────────────────────────────────────────────
# Once PICKUP_RADIUS is hit the robot can no longer see the puck (too close).
# It creeps forward for BLIND_DRIVE_SECS so the puck ends up seated under the
# gripper before the arm drops.  Increase if arm misses; decrease if overshoot.
BLIND_DRIVE_SECS = 1.2
CREEP_SPEED      = 0.35

# ── Failed-grab back-off ──────────────────────────────────────────────────────
FAIL_BACKOFF_SECS = 0.8   # how far back to reverse after a failed grab

# ── Odometry (time-based) ─────────────────────────────────────────────────────
# Measure your robot travelling at SPEED=0.6 over a known distance and set this.
FORWARD_CM_PER_SEC = 20.0  # cm/s at SPEED=0.6  ← tune this value

# ── Arm & Gripper servo pins (BOARD numbering) ────────────────────────────────
GRIPPER_PIN      = 12   # BCM 18 → BOARD 12
ARM_PIN          = 29   # BOARD 29

# ── Arm & Gripper angles ──────────────────────────────────────────────────────
ARM_UP_ANGLE     = 0    # degrees – arm raised / travel position
ARM_DOWN_ANGLE   = 250  # degrees – arm lowered to puck height (300° servo)
GRIPPER_OPEN     = 0    # degrees – gripper open
GRIPPER_CLOSED   = 180  # degrees – gripper closed


# ═══════════════════════════════════════════════════════════════════════════════
#  MOTOR CONTROLLER
# ═══════════════════════════════════════════════════════════════════════════════

MOTOR_PINS = {
    "fl": (11, 15, 13),
    "fr": (22, 16, 18),
    "rl": (19, 21, 23),
    "rr": (32, 24, 26),
}

MOTOR_POLARITY = {
    "fl": 1,
    "fr": 1,
    "rl": 1,
    "rr": 1,
}


class MotorController:

    def __init__(self):
        self._pwm = {}
        if HARDWARE_AVAILABLE:
            GPIO.setmode(GPIO.BOARD)
            for key, (en, fwd, rev) in MOTOR_PINS.items():
                GPIO.setup(en,  GPIO.OUT)
                GPIO.setup(fwd, GPIO.OUT)
                GPIO.setup(rev, GPIO.OUT)
                pwm = GPIO.PWM(en, 100)
                pwm.start(0)
                self._pwm[key] = (pwm, fwd, rev)

    def _drive(self, key, val):
        val *= MOTOR_POLARITY[key]
        duty = abs(val) * 100
        if HARDWARE_AVAILABLE:
            pwm, fwd, rev = self._pwm[key]
            if val > 0:
                GPIO.output(fwd, 1); GPIO.output(rev, 0)
            elif val < 0:
                GPIO.output(fwd, 0); GPIO.output(rev, 1)
            else:
                GPIO.output(fwd, 0); GPIO.output(rev, 0)
            pwm.ChangeDutyCycle(duty)
        else:
            if val != 0:
                print(f"  [{key}] {val:+.2f}")

    def set_motors(self, fl, fr, rl, rr):
        self._drive("fl", fl)
        self._drive("fr", fr)
        self._drive("rl", rl)
        self._drive("rr", rr)

    def stop(self):
        self.set_motors(0, 0, 0, 0)

    def cleanup(self):
        self.stop()
        if HARDWARE_AVAILABLE:
            for pwm, _, _ in self._pwm.values():
                pwm.stop()
            GPIO.cleanup()

    # ── Named moves ───────────────────────────────────────────────────────────
    def forward(self,    s=SPEED): self.set_motors( s,  s,  s,  s)
    def backward(self,   s=SPEED): self.set_motors(-s, -s, -s, -s)
    def left(self,       s=SPEED): self.set_motors(-s,  s,  s, -s)
    def right(self,      s=SPEED): self.set_motors( s, -s, -s,  s)
    def fwd_left(self,   s=SPEED): self.set_motors( 0,  s,  s,  0)
    def fwd_right(self,  s=SPEED): self.set_motors( s,  0,  0,  s)
    def bck_left(self,   s=SPEED): self.set_motors(-s,  0,  0, -s)
    def bck_right(self,  s=SPEED): self.set_motors( 0, -s, -s,  0)
    def spin_right(self, s=SPEED): self.set_motors( s, -s,  s, -s)
    def spin_left(self,  s=SPEED): self.set_motors(-s,  s, -s,  s)

    def move(self, name: str, s: float = SPEED):
        actions = {
            "forward":   self.forward,
            "backward":  self.backward,
            "left":      self.left,
            "right":     self.right,
            "fwd_left":  self.fwd_left,
            "fwd_right": self.fwd_right,
            "bck_left":  self.bck_left,
            "bck_right": self.bck_right,
            "stop":      lambda s: self.stop(),
        }
        if name in actions:
            actions[name](s)


