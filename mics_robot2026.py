class CameraThread(threading.Thread):

    def __init__(self, mc: MotorController, state: dict):
        super().__init__(daemon=True)
        self.mc    = mc
        self.state = state

    def run(self):
        picam2 = Picamera2()
        picam2.configure(picam2.create_preview_configuration(
            main={"format": "RGB888", "size": (FRAME_W, FRAME_H)}
        ))
        picam2.start()
        time.sleep(1)

        while self.state["running"]:
            frame = picam2.capture_array()
            hsv   = cv2.cvtColor(frame, cv2.COLOR_RGB2HSV)

            # ── Detect all pucks ──────────────────────────────────────────────
            mask = cv2.inRange(hsv, np.array([0, 80, 80]), np.array([179, 255, 255]))
            mask = cv2.morphologyEx(mask, cv2.MORPH_OPEN, np.ones((5, 5), np.uint8))
            contours, _ = cv2.findContours(mask, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)

            best      = None   # (x, y, r, dist) of closest target-color puck
            best_area = 0

            for c in contours:
                area = cv2.contourArea(c)
                if area < MIN_PUCK_AREA:
                    continue

                peri = cv2.arcLength(c, True)
                if peri == 0:
                    continue
                if 4 * np.pi * (area / (peri * peri)) < MIN_CIRCULARITY:
                    continue

                (x, y), r = cv2.minEnclosingCircle(c)
                x, y, r   = int(x), int(y), int(r)

                roi = hsv[max(0,y-5):y+5, max(0,x-5):x+5]
                if roi.size == 0:
                    continue

                h_v, s_v, v_v = np.mean(roi, axis=(0, 1)).astype(int)
                color = classify_color(h_v, s_v, v_v)
                dist  = estimate_distance(r)
                is_target = (color == self.state["target"])

                # Track the best (largest = closest) target puck
                if is_target and area > best_area:
                    best_area = area
                    best = (x, y, r, dist)

                # Draw all pucks: thick+crosshair for target, thin for others
                ring_color = (0, 0, 255) if is_target else (0, 255, 0)
                thickness  = 4 if is_target else 2
                cv2.circle(frame, (x, y), r, ring_color, thickness)
                cv2.putText(frame, f"{color} {dist}cm",
                            (x - 40, y - r - 10),
                            cv2.FONT_HERSHEY_SIMPLEX, 0.6, (255, 255, 255), 2)
                if is_target:
                    cv2.line(frame, (x-16, y), (x+16, y), (0, 0, 255), 2)
                    cv2.line(frame, (x, y-16), (x, y+16), (0, 0, 255), 2)

            # ── AUTO drive logic ──────────────────────────────────────────────
            if self.state["auto"] and not self.state["estop"]:

                if self.state["pickup_active"]:
                    # Mid-pickup pause – just hold still
                    self.mc.stop()

                elif best:
                    x, y, r, dist = best
                    offset = x - FRAME_W // 2

                    if r >= PICKUP_RADIUS:
                        # Reached the puck – stop and start pickup pause timer
                        self.mc.stop()
                        if not self.state["pickup_active"]:
                            self.state["pickup_active"] = True
                            threading.Thread(
                                target=self._pickup_pause, daemon=True
                            ).start()

                    elif offset < -CENTER_TOLERANCE:
                        self.mc.left()

                    elif offset > CENTER_TOLERANCE:
                        self.mc.right()

                    else:
                        self.mc.forward()

                else:
                    self.mc.forward(0.2)

            # ── HUD overlay ───────────────────────────────────────────────────
            self._draw_hud(frame, best)

            cv2.imshow("Robot Camera", frame)
            cv2.waitKey(1)

        picam2.stop()
        cv2.destroyAllWindows()

    def _pickup_pause(self):
        """Hold stopped for PICKUP_PAUSE seconds, then resume AUTO."""
        time.sleep(PICKUP_PAUSE)
        self.state["pickup_active"] = False

    def _draw_hud(self, frame, best):
        mode   = "AUTO" if self.state["auto"] else "MANUAL"
        target = self.state["target"]
        estop  = self.state["estop"]
        pickup = self.state["pickup_active"]

        # Top-left status lines
        lines = [
            f"MODE: {mode}   TARGET: {target}",
            f"PUCK: {'in range' if best else 'searching...'}",
        ]
        for i, line in enumerate(lines):
            cv2.putText(frame, line, (10, 28 + i * 26),
                        cv2.FONT_HERSHEY_SIMPLEX, 0.65, (220, 220, 220), 2)

        # Bottom banner for special states
        if estop:
            cv2.rectangle(frame, (0, FRAME_H - 55), (FRAME_W, FRAME_H), (0, 0, 160), -1)
            cv2.putText(frame, "  E-STOP  (release Space to continue)",
                        (10, FRAME_H - 16),
                        cv2.FONT_HERSHEY_SIMPLEX, 0.75, (255, 255, 255), 2)
        elif pickup:
            cv2.rectangle(frame, (0, FRAME_H - 55), (FRAME_W, FRAME_H), (0, 130, 0), -1)
            cv2.putText(frame, "  PICKUP – grabbing puck...",
                        (10, FRAME_H - 16),
                        cv2.FONT_HERSHEY_SIMPLEX, 0.75, (255, 255, 255), 2)


