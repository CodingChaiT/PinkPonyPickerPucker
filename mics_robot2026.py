class RobotGUI:

    KEY_MAP = {
        "w": "forward",   "Up":    "forward",
        "s": "backward",  "Down":  "backward",
        "a": "left",      "Left":  "left",
        "d": "right",     "Right": "right",
        "q": "fwd_left",
        "e": "fwd_right",
        "z": "bck_left",
        "c": "bck_right",
    }

    def __init__(self, root: tk.Tk, mc: MotorController, state: dict):
        self.root  = root
        self.mc    = mc
        self.state = state

        self._active_move  = None
        self._running_move = False
        self._speed        = SPEED

        root.title("Hungry Hungry Robots")
        root.configure(bg=BG)
        root.resizable(False, False)

        self._build_header()
        self._build_status_bar()
        self._build_color_selector()
        self._build_auto_btn()
        self._build_dpad()
        self._bind_keys()

        root.protocol("WM_DELETE_WINDOW", self._on_close)

    def _build_header(self):
        f = tk.Frame(self.root, bg=BG, pady=12)
        f.pack(fill="x")
        try:
            font = tkfont.Font(family="Courier New", size=14, weight="bold")
        except Exception:
            font = ("TkFixedFont", 14, "bold")
        tk.Label(f, text="◈  HUNGRY HUNGRY ROBOTS  ◈",
                 font=font, fg=ACCENT, bg=BG).pack()
        hw  = "HARDWARE" if HARDWARE_AVAILABLE else "SIMULATION"
        col = "#44cc88" if HARDWARE_AVAILABLE else "#cc8844"
        tk.Label(f, text=f"● {hw}",
                 font=("Courier New", 9), fg=col, bg=BG).pack()

    def _build_color_selector(self):
        outer = tk.Frame(self.root, bg=BG, pady=6)
        outer.pack(fill="x", padx=16)
        tk.Label(outer, text="TARGET COLOR",
                 font=("Courier New", 9), fg=FG_DIM, bg=BG).pack(anchor="w")
        row = tk.Frame(outer, bg=BG)
        row.pack(pady=(4, 0))

        self._color_btns = {}
        try:
            cf = tkfont.Font(family="Courier New", size=11, weight="bold")
        except Exception:
            cf = ("TkFixedFont", 11, "bold")

        for color in ("Red", "Blue", "Green", "Yellow"):
            idle, act = COLOR_BTN_THEME[color]
            btn = tk.Label(row, text=color, width=8,
                           font=cf, fg=FG, bg=idle,
                           relief="flat", cursor="hand2",
                           highlightbackground=BORDER, highlightthickness=1,
                           padx=6, pady=6)
            btn.pack(side="left", padx=4)
            btn.bind("<ButtonPress-1>", lambda e, c=color: self._pick_color(c))
            btn.bind("<Enter>",  lambda e, b=btn, a=act: b.config(bg=a))
            btn.bind("<Leave>",  lambda e, c=color, b=btn: self._restore_color(c, b))
            self._color_btns[color] = (btn, idle, act)

        self._pick_color(self.state["target"])

    def _pick_color(self, color):
        self.state["target"] = color
        for c, (btn, idle, act) in self._color_btns.items():
            btn.config(bg=act if c == color else idle)
        self._refresh_status()

    def _restore_color(self, color, btn):
        _, idle, act = self._color_btns[color]
        btn.config(bg=act if color == self.state["target"] else idle)

    def _build_auto_btn(self):
        outer = tk.Frame(self.root, bg=BG, pady=8)
        outer.pack(fill="x", padx=16)
        try:
            af = tkfont.Font(family="Courier New", size=12, weight="bold")
        except Exception:
            af = ("TkFixedFont", 12, "bold")
        self._auto_lbl = tk.Label(
            outer, text="▶  START AUTO",
            font=af, fg=FG, bg=AUTO_OFF_BG,
            relief="flat", cursor="hand2",
            highlightbackground=BORDER, highlightthickness=1,
            padx=10, pady=9)
        self._auto_lbl.pack(fill="x")
        self._auto_lbl.bind("<ButtonPress-1>", lambda e: self._toggle_auto())
        tk.Label(outer, text="press F to toggle",
                 font=("Courier New", 8), fg=FG_DIM, bg=BG).pack(pady=(2, 0))

    def _toggle_auto(self):
        self.state["auto"] = not self.state["auto"]
        if self.state["auto"]:
            self._auto_lbl.config(text="⏹  STOP AUTO", bg=AUTO_ON_BG)
            self._running_move = False
            self._active_move  = None
            self.mc.stop()
        else:
            self._auto_lbl.config(text="▶  START AUTO", bg=AUTO_OFF_BG)
            self.state["pickup_active"] = False
            self.mc.stop()
        self._refresh_status()

    def _build_dpad(self):
        outer = tk.Frame(self.root, bg=BG)
        outer.pack(expand=True)
        tk.Label(outer, text="MANUAL DRIVE",
                 font=("Courier New", 9), fg=FG_DIM, bg=BG).pack(pady=(4, 2))

        pad = tk.Frame(outer, bg=PANEL, padx=14, pady=14,
                       highlightbackground=BORDER, highlightthickness=1)
        pad.pack()

        layout = [
            (0, 0, "↖", "fwd_left"),  (0, 1, "↑", "forward"),  (0, 2, "↗", "fwd_right"),
            (1, 0, "←", "left"),      (1, 1, "■", "stop"),      (1, 2, "→", "right"),
            (2, 0, "↙", "bck_left"),  (2, 1, "↓", "backward"),  (2, 2, "↘", "bck_right"),
        ]

        self._dpad = {}
        for row, col, sym, move in layout:
            is_stop = (move == "stop")
            btn = self._make_btn(pad, sym, move, is_stop)
            btn.grid(row=row, column=col, padx=5, pady=5)
            self._dpad[move] = btn

        sf = tk.Frame(outer, bg=BG, pady=8)
        sf.pack(fill="x")
        tk.Label(sf, text="SPEED", font=("Courier New", 9),
                 fg=FG_DIM, bg=BG).pack(side="left", padx=(14, 6))
        self._spd_var = tk.DoubleVar(value=SPEED)
        tk.Scale(sf, from_=0.1, to=1.0, resolution=0.05,
                 orient="horizontal", variable=self._spd_var,
                 bg=PANEL, fg=FG, troughcolor=BTN_IDLE,
                 highlightthickness=0, length=280,
                 bd=0, relief="flat").pack(side="left")

    def _make_btn(self, parent, sym, move, is_stop):
        idle = STOP_IDLE if is_stop else BTN_IDLE
        act  = STOP_ACT  if is_stop else BTN_ACT
        try:
            f = tkfont.Font(family="Courier New", size=19, weight="bold")
        except Exception:
            f = ("TkFixedFont", 19, "bold")
        btn = tk.Label(parent, text=sym, width=3, height=1,
                       font=f, fg=FG, bg=idle,
                       relief="flat", cursor="hand2",
                       highlightbackground=BORDER, highlightthickness=1,
                       padx=8, pady=8)
        btn.bind("<ButtonPress-1>",
                 lambda e, m=move, i=idle, a=act, b=btn: self._press(m, b, i, a))
        btn.bind("<ButtonRelease-1>",
                 lambda e, m=move, i=idle, b=btn: self._release(m, b, i))
        btn.bind("<Enter>",
                 lambda e, b=btn, idle=idle:
                     b.config(bg="#3a1a1a" if idle == STOP_IDLE else BTN_HOV))
        btn.bind("<Leave>",
                 lambda e, b=btn, m=move, i=idle:
                     b.config(bg=i) if self._active_move != m else None)
        return btn

    def _press(self, move, btn, idle, act):
        if self.state["auto"]:
            self.state["auto"]          = False
            self.state["pickup_active"] = False
            self._auto_lbl.config(text="▶  START AUTO", bg=AUTO_OFF_BG)
        btn.config(bg=act)
        self._active_move  = move
        self._running_move = True
        self._do_move(move)
        threading.Thread(target=self._repeat, args=(move,), daemon=True).start()
        self._refresh_status(move)

    def _release(self, move, btn, idle):
        btn.config(bg=idle)
        self._running_move = False
        self._active_move  = None
        self.mc.stop()
        self._refresh_status("stop")

    def _repeat(self, move):
        time.sleep(0.1)
        while self._running_move and self._active_move == move:
            self._do_move(move)
            time.sleep(0.05)

    def _do_move(self, move):
        self.mc.move(move, self._spd_var.get())

    def _bind_keys(self):
        for key, move in self.KEY_MAP.items():
            self.root.bind(f"<KeyPress-{key}>",   lambda e, m=move: self._key_dn(m))
            self.root.bind(f"<KeyRelease-{key}>", lambda e, m=move: self._key_up(m))
        self.root.bind("<KeyPress-space>",   lambda e: self._estop_on())
        self.root.bind("<KeyRelease-space>", lambda e: self._estop_off())
        self.root.bind("<KeyPress-f>", lambda e: self._toggle_auto())

    def _key_dn(self, move):
        if self.state["auto"]:
            self.state["auto"]          = False
            self.state["pickup_active"] = False
            self._auto_lbl.config(text="▶  START AUTO", bg=AUTO_OFF_BG)
        if self._active_move == move:
            return
        self._active_move = move
        self._do_move(move)
        self._refresh_status(move)
        if move in self._dpad:
            self._dpad[move].config(bg=BTN_ACT)

    def _key_up(self, move):
        if self.state["estop"]:
            return
        if self._active_move == move:
            self._active_move = None
            self.mc.stop()
            self._refresh_status("stop")
        if move in self._dpad:
            self._dpad[move].config(bg=BTN_IDLE)

    def _estop_on(self):
        self.state["estop"]    = True
        self._running_move     = False
        self._active_move      = None
        self.mc.stop()
        self._refresh_status("stop")

    def _estop_off(self):
        self.state["estop"] = False
        self._refresh_status("stop")

    MOVE_LABELS = {
        "forward":   "▲  FORWARD",
        "backward":  "▼  BACKWARD",
        "left":      "◀  STRAFE LEFT",
        "right":     "▶  STRAFE RIGHT",
        "fwd_left":  "↖  FORWARD-LEFT",
        "fwd_right": "↗  FORWARD-RIGHT",
        "bck_left":  "↙  BACKWARD-LEFT",
        "bck_right": "↘  BACKWARD-RIGHT",
        "stop":      "■  STOPPED",
    }

    def _build_status_bar(self):
        bar = tk.Frame(self.root, bg=PANEL, pady=8,
                       highlightbackground=BORDER, highlightthickness=1)
        bar.pack(fill="x", side="bottom")
        try:
            sf = tkfont.Font(family="Courier New", size=10, weight="bold")
        except Exception:
            sf = ("TkFixedFont", 10, "bold")
        self._status_var = tk.StringVar(value="■  STOPPED  |  MANUAL  |  Blue")
        tk.Label(bar, textvariable=self._status_var,
                 font=sf, fg=FG, bg=PANEL).pack()
        tk.Label(bar,
                 text="WASD/Arrows=drive  Q/E/Z/C=diag  Space=E-STOP  F=AUTO",
                 font=("Courier New", 8), fg=FG_DIM, bg=PANEL).pack(pady=(2, 0))

    def _refresh_status(self, move: str = "stop"):
        label = self.MOVE_LABELS.get(move, "■  STOPPED")
        mode  = "AUTO" if self.state["auto"] else "MANUAL"
        color = self.state["target"]
        self._status_var.set(f"{label}  |  {mode}  |  {color}")

    def _on_close(self):
        self._running_move    = False
        self.state["running"] = False
        self.state["auto"]    = False
        self.mc.cleanup()
        self.root.destroy()


