class MotorController:
    """
    Thin wrapper around MotorKit that exposes set_motors(fl, fr, rl, rr).
    Each argument is a throttle in the range [-1.0, 1.0].
    """

    def __init__(self):
        if HARDWARE_AVAILABLE:
            self.kit = MotorKit(i2c=board.I2C())
            self._motors = [
                self.kit.motor1,  # Front-Left
                self.kit.motor2,  # Front-Right
                self.kit.motor3,  # Rear-Left
                self.kit.motor4,  # Rear-Right
            ]
        else:
            self.kit = None
            self._motors = None

    def set_motors(self, fl: float, fr: float, rl: float, rr: float):
        """Apply polarity correction and send throttle to each motor."""
        values = {
            "fl": fl * MOTOR_POLARITY["fl"],
            "fr": fr * MOTOR_POLARITY["fr"],
            "rl": rl * MOTOR_POLARITY["rl"],
            "rr": rr * MOTOR_POLARITY["rr"],
        }
        if HARDWARE_AVAILABLE:
            self._motors[0].throttle = max(-1.0, min(1.0, values["fl"]))
            self._motors[1].throttle = max(-1.0, min(1.0, values["fr"]))
            self._motors[2].throttle = max(-1.0, min(1.0, values["rl"]))
            self._motors[3].throttle = max(-1.0, min(1.0, values["rr"]))
        else:
            print(f"  FL={values['fl']:+.2f}  FR={values['fr']:+.2f}  "
                  f"RL={values['rl']:+.2f}  RR={values['rr']:+.2f}")

    def stop(self):
        self.set_motors(0, 0, 0, 0)

    def cleanup(self):
        self.stop()


