"""
Mecanum Wheel Controller
========================
Controls a 4-wheel mecanum drive robot using the SB Components Motor Shield
for Raspberry Pi (L293D-based, GPIO-controlled via RPi.GPIO).

Wiring:
  MOTOR1 → Front-Left  wheel
  MOTOR2 → Front-Right wheel
  MOTOR3 → Rear-Left   wheel
  MOTOR4 → Rear-Right  wheel

  SB Components Motor Shield – BOARD pin assignments (from PiMotor.py):
  ┌─────────┬────────┬─────────┬─────────┐
  │  Motor  │ Enable │ Forward │ Reverse │
  ├─────────┼────────┼─────────┼─────────┤
  │ MOTOR1  │  11    │   15    │   13    │
  │ MOTOR2  │  22    │   16    │   18    │
  │ MOTOR3  │  19    │   21    │   23    │
  │ MOTOR4  │  32    │   24    │   26    │
  └─────────┴────────┴─────────┴─────────┘
  All pin numbers are physical BOARD numbers.

  If a wheel spins the wrong direction, swap its two motor leads on the
  terminal block, or negate its throttle in the MOTOR_POLARITY dict below.

Install dependencies:
  sudo apt-get update && sudo apt-get install -y python3-pip python3-tk
  pip3 install RPi.GPIO
  # (RPi.GPIO is usually pre-installed on Raspberry Pi OS)

Usage:
  python3 mecanum_controller.py
"""

