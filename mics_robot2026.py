        self._result = result
        self._event  = event

        self.title("Grab Confirmation")
        self.configure(bg=BG)
        self.resizable(False, False)
        self.grab_set()
        self.lift()
        self.focus_force()

        # Centre over parent window
        self.update_idletasks()
        pw = parent.winfo_width()
        ph = parent.winfo_height()
        px = parent.winfo_rootx()
        py = parent.winfo_rooty()
        w, h = 360, 170
        self.geometry(f"{w}x{h}+{px+(pw-w)//2}+{py+(ph-h)//2}")

        try:
            hf = tkfont.Font(family="Courier New", size=13, weight="bold")
            bf = tkfont.Font(family="Courier New", size=11, weight="bold")
            sf = tkfont.Font(family="Courier New", size=9)
        except Exception:
            hf = bf = sf = ("TkFixedFont", 11, "bold")

        tk.Label(self, text="✔  PUCK GRABBED?",
                 font=hf, fg=ACCENT, bg=BG, pady=14).pack()

        tk.Label(self, text="Did the gripper successfully grab the puck?",
                 font=sf, fg=FG_DIM, bg=BG).pack()

        btn_row = tk.Frame(self, bg=BG, pady=14)
        btn_row.pack()

        yes_btn = tk.Label(btn_row, text="✔  YES  (Y)",
                           font=bf, fg=FG, bg="#1a7a3a",
                           relief="flat", cursor="hand2",
                           highlightbackground=BORDER, highlightthickness=1,
                           padx=12, pady=9)
        yes_btn.pack(side="left", padx=12)
        yes_btn.bind("<ButtonPress-1>", lambda e: self._answer(True))
        yes_btn.bind("<Enter>", lambda e: yes_btn.config(bg="#22a050"))
        yes_btn.bind("<Leave>", lambda e: yes_btn.config(bg="#1a7a3a"))

        no_btn = tk.Label(btn_row, text="✖  NO  (N)",
                          font=bf, fg=FG, bg=STOP_IDLE,
                          relief="flat", cursor="hand2",
                          highlightbackground=BORDER, highlightthickness=1,
                          padx=12, pady=9)
        no_btn.pack(side="left", padx=12)
        no_btn.bind("<ButtonPress-1>", lambda e: self._answer(False))
        no_btn.bind("<Enter>", lambda e: no_btn.config(bg="#4a2020"))
        no_btn.bind("<Leave>", lambda e: no_btn.config(bg=STOP_IDLE))

